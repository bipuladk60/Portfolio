function inside(lon: number, lat: number, poly: LonLat[]) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const isLand = (lon: number, lat: number) =>
  LAND.some((p) => inside(lon, lat, p)) && !WATER.some((p) => inside(lon, lat, p));

/** Every land dot as one path of zero-length segments (rendered with round caps): one DOM node. */
function buildDots(step: number) {
  const parts: string[] = [];
  for (let lat = LAT_TOP - step / 2; lat > LAT_BOTTOM; lat -= step) {
    for (let lon = -180 + step / 2; lon < 180; lon += step) {
      if (isLand(lon, lat)) {
        const [x, y] = project(lon, lat);
        parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
      }
    }
  }
  return parts.join("");
}

/** The faint ocean grid: every dot position, land or not. */
function buildGrid(step: number) {
  const parts: string[] = [];
  for (let lat = LAT_TOP - step / 2; lat > LAT_BOTTOM; lat -= step * 2) {
    for (let lon = -180 + step / 2; lon < 180; lon += step * 2) {
      const [x, y] = project(lon, lat);
      parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
    }
  }
  return parts.join("");
}

/** Great-circle samples between two points (spherical linear interpolation), projected. */
function buildArc(a: { lat: number; lon: number }, b: { lat: number; lon: number }, n: number) {
  const r = Math.PI / 180;
  const v = (la: number, lo: number) => [
    Math.cos(la * r) * Math.cos(lo * r),
    Math.cos(la * r) * Math.sin(lo * r),
    Math.sin(la * r),
  ];
  const A = v(a.lat, a.lon);
  const B = v(b.lat, b.lon);
  const d = Math.acos(A[0] * B[0] + A[1] * B[1] + A[2] * B[2]);
  const pts: [number, number][] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const s1 = Math.sin((1 - t) * d) / Math.sin(d);
    const s2 = Math.sin(t * d) / Math.sin(d);
    const p = A.map((x, k) => s1 * x + s2 * B[k]);
    const lat = Math.asin(p[2]) / r;
    const lon = Math.atan2(p[1], p[0]) / r;
    pts.push(project(lon, lat));
  }
  return { pts, degrees: d / r };
}

export const DOT_STEP = 3;
export const LAND_DOTS = buildDots(DOT_STEP);
export const OCEAN_GRID = buildGrid(DOT_STEP);
const arc = buildArc(KTM, HBG, 180);
export const ARC_POINTS = arc.pts;
export const ARC_PATH = arc.pts
  .map(([x, y], i) => `${i ? "L" : "M"}${x.toFixed(2)} ${y.toFixed(2)}`)
  .join("");
/** Central angle of the route; distance shown is derived from this, not hard-coded. */
export const ARC_KM = Math.round((arc.degrees * Math.PI * 6371) / 180);

export const toPct = ([x, y]: [number, number]) => ({
  left: `${(x / MAP_W) * 100}%`,
  top: `${(y / MAP_H) * 100}%`,
});
